function CM = cc_car_model(T, P, primFcn)
%CC_CAR_MODEL  The vehicle model, prepared so a search can use it.
%
%   CM = CC_CAR_MODEL(T)                         uses YOUR car_primitives
%   CM = CC_CAR_MODEL(T, P)
%   CM = CC_CAR_MODEL(T, P, @cc_primitives_probe)   the simulator instead
%
%   The motion space comes from CAR_PRIMITIVES, which you write: it
%   computes the five moves from the bicycle model. Pass
%   @cc_primitives_probe to use the measured version instead -- the one
%   that drives CC_STEP. That is what CHECK_TOOLS does, so the toolbox
%   can be tested before you have written anything.
%
%   Returns everything CAR_NEIGHBORS and CC_POSE_INDEX need:
%     CM.prim(k)   one motion primitive: .delta .dx .dy .dth .cost .pts
%     CM.body      the car's outline as sample points, in the car's own
%                  frame -- what the collision test moves around
%     CM.R .C .nTheta .nNodes    the size of the pose space
%     CM.poseCell  metres per position cell
%     CM.T .P
%
%   ------------------------------------------------------------------
%   WHAT A MOTION PRIMITIVE IS
%
%   Up to chapter 08 the question was: "from this cell, which cells can
%   I step to?" The answer was four or eight neighbours, and it had
%   nothing to do with the car.
%
%   Here the question is: "from this POSE, which poses can the car
%   actually reach?" A pose is (x, y, theta) -- where the car is AND
%   which way it points. The answer is: hold one steering angle, drive
%   P.arc metres, and see where you end up. Five steering angles, five
%   neighbours:
%
%       -22   -11    0    +11   +22   degrees
%
%   Each one is integrated with the SAME bicycle model that CC_STEP uses
%   to drive the car. That is the whole point: the search space is
%   generated by the vehicle, so anything the search finds, the vehicle
%   can do. Nothing is bolted on afterwards.
%
%   WHY P.arc IS 11.9 CENTIMETRES AND NOT A ROUND NUMBER
%   At full lock the car turns at cos(beta)*tan(deltaMax)/L = 3.30 rad
%   per metre driven. The search keeps 16 headings, 22.5 degrees apart.
%   So an arc of 0.3927 / 3.30 = 0.119 m turns exactly ONE heading step.
%   Pick a round 0.15 m instead and full lock lands between two headings
%   every time, the search rounds it, and the stored pose drifts away
%   from the pose the car would really be in.
%
%   HOW BIG THE SEARCH SPACE IS
%   29 by 65 positions times 16 headings = 30160 nodes, against 1885
%   cells for the same track without headings. Sixteen times the work,
%   for an answer the car can drive. That is the price, and it is worth
%   knowing before you are surprised by it.
%
%   See also CAR_NEIGHBORS, CC_POSE_INDEX, CC_STEP, CC_TRACK.

if nargin < 2 || isempty(P)
    P = T.P;
end
if nargin < 3 || isempty(primFcn)
    primFcn = @car_primitives;
end

CM.P = P;
CM.T = T;

% ---- the pose space ---------------------------------------------------
CM.poseCell = P.poseCell;
CM.C        = round(P.worldX / P.poseCell);
CM.R        = round(P.worldY / P.poseCell);
CM.nTheta   = P.nTheta;
CM.dTheta   = 2*pi / P.nTheta;
CM.nNodes   = CM.R * CM.C * CM.nTheta;

% ---- the primitives: the motion space, read off the simulator --------
try
    CM.prim = primFcn(P);
catch err
    if strcmp(err.identifier, 'task:todo')
        error('cc_car_model:noPrimitives', ...
            ['The motion space is missing: tasks/car_primitives.m is still\n' ...
             'the skeleton, and everything from here on is built on it.\n\n' ...
             'Write it (ANLEITUNGEN/08_vehicle_neighbors.md), or ask for the\n' ...
             'reference set instead:\n' ...
             '    CM = cc_car_model(T, P, @cc_primitives_probe)']);
    end
    rethrow(err)
end

local_checkPrimitives(CM.prim, P);

% ---- the car's outline, as points to test -----------------------------
% Sampled a little finer than T.Mfine, so no wall can slip between two
% samples. The centre line is included as well: a wall narrower than the
% car could otherwise sit inside the rectangle untouched.
step = T.fineSize / 2;
hl = P.bodyL / 2;
hw = P.bodyW / 2;

corners = [ hl,  hw;  hl, -hw; -hl, -hw; -hl,  hw;  hl,  hw];
body = zeros(0,2);
for e = 1:4
    n = max(2, ceil(hypot(corners(e+1,1)-corners(e,1), ...
                          corners(e+1,2)-corners(e,2)) / step) + 1);
    body = [body; ...
            linspace(corners(e,1), corners(e+1,1), n).', ...
            linspace(corners(e,2), corners(e+1,2), n).']; %#ok<AGROW>
end
n = max(2, ceil(2*hl / step) + 1);
body = [body; linspace(-hl, hl, n).', zeros(n,1)];

CM.body = unique(body, 'rows').';      % 2-by-N, ready to be rotated
end

% -----------------------------------------------------------------------
function local_checkPrimitives(prim, P)
%LOCAL_CHECKPRIMITIVES  Catch a broken motion space here, not 2000 lines later.
%
%   A search built on primitives that all sit at the origin does not
%   fail -- it quietly explores nothing and reports that there is no
%   route. These four checks turn that into a sentence.

if ~isstruct(prim) || numel(prim) ~= numel(P.steerLevels)
    error('cc_car_model:primCount', ...
        'car_primitives returned %d primitives, expected %d.', ...
        numel(prim), numel(P.steerLevels));
end

need = {'delta','dx','dy','dth','pts','len','cost'};
missing = need(~isfield(prim, need));
if ~isempty(missing)
    error('cc_car_model:primFields', ...
        'car_primitives is missing the field(s): %s', strjoin(missing, ', '));
end

for k = 1:numel(prim)
    d = hypot(prim(k).dx, prim(k).dy);
    if d < 0.5 * P.arc
        error('cc_car_model:primShort', ...
            ['Primitive %d (%.0f deg) moves the car only %.4f m, but it is\n' ...
             'supposed to drive %.3f m. Is the probe loop running at all,\n' ...
             'and are dx/dy being written?'], k, prim(k).delta, d, P.arc);
    end
    if d > 1.05 * P.arc
        error('cc_car_model:primLong', ...
            ['Primitive %d (%.0f deg) ends %.4f m away, further than the\n' ...
             '%.3f m it drove -- impossible along an arc. The last step is\n' ...
             'probably not being cut at P.arc (TODO 3).'], ...
            k, prim(k).delta, d, P.arc);
    end
    if size(prim(k).pts, 2) ~= 3 || size(prim(k).pts, 1) < 1
        error('cc_car_model:primPts', ...
            'Primitive %d has no usable .pts; it must be N-by-3.', k);
    end
end

% Full lock has to turn exactly one heading step, or the lattice drifts.
[~, iMax] = max(abs([prim.delta]));
oneBin = 2*pi / P.nTheta;
if abs(abs(prim(iMax).dth) - oneBin) > 0.02 * oneBin
    warning('cc_car_model:primBin', ...
        ['Full lock turns the car %.2f deg, but one heading step is %.2f deg.\n' ...
         'The search will round every full-lock move, and the stored pose\n' ...
         'will drift from the real one. Check that the arc is cut at P.arc.'], ...
        rad2deg(abs(prim(iMax).dth)), rad2deg(oneBin));
end
end
